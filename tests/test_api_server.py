"""Tests for the FastAPI service (spec 15.1, prompt 21).

The recordings are generated by :mod:`eval.synthetic_audio`, so every stage
except MFA runs for real against a real envelope of five readers.

One seam is used deliberately. :func:`rostrum.api.server.analyze_endpoint`
always runs the ASR mismatch check, which is correct - it is the only stage
that can produce Reject mode, and skipping it for a user upload would be a
hole. Generated tone bursts are not speech, so the recogniser hears nothing and
that check rejects them, as it should. The reference-mode tests therefore patch
the module's ``analyze`` with the alignment the generator laid down and the
check switched off, which is exactly what the evaluation harness does; the
rejection path is then tested *without* the patch, against the real check.
"""

from __future__ import annotations

import functools
import json

import pytest
from eval.synthetic_audio import DEMO_TEXT, demo_library, make_utterance, parse_text
from fastapi.testclient import TestClient

import rostrum.api.server as server
import rostrum.pipeline as pipeline
from rostrum.api.models import AnalysisResultModel
from rostrum.config import load_config

MB = 1024 * 1024


@pytest.fixture(scope="module")
def cfg():
    return load_config()


@pytest.fixture(scope="module")
def work(tmp_path_factory):
    return tmp_path_factory.mktemp("api")


@pytest.fixture(scope="module")
def library(cfg, work):
    built, _ = demo_library(cfg, work / "library", n_readers=5)
    return built


@pytest.fixture(scope="module")
def rushed(work):
    """A participant who rushes one clause of the demo text."""
    spoken = parse_text(DEMO_TEXT)
    rate = [1.0] * len(spoken.words)
    rate[4:8] = [1.9] * 4
    return make_utterance("api_rushing", work, text=spoken, seed=4242, rate_scale=rate)


@pytest.fixture
def client(cfg, library, monkeypatch):
    """A client whose config and library are the generated ones."""
    monkeypatch.setattr(server, "get_config", lambda: cfg)
    monkeypatch.setattr(server, "get_library", lambda: library)
    monkeypatch.setattr(server, "get_store", lambda: server.ClipStore.from_config(cfg))
    return TestClient(server.app)


@pytest.fixture
def offline_client(client, rushed, monkeypatch):
    """A client that skips the ASR check and uses the generator's alignment."""
    monkeypatch.setattr(
        server,
        "analyze",
        functools.partial(pipeline.analyze, check_text_match=False, alignment=rushed.alignment),
    )
    return client


def _post(client, rushed, transcript: str = DEMO_TEXT, **extra):
    """POST the generated recording to ``/analyze``."""
    data = {"transcript": transcript, **extra}
    return client.post(
        "/analyze",
        files={"audio": (f"{rushed.file_id}.wav", rushed.path.read_bytes(), "audio/wav")},
        data=data,
    )


