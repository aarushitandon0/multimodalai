def test_a_mismatched_transcript_is_rejected_not_scored(client, rushed):
    """Reject mode is a finding, so it is a 200 with no score - never a 500."""
    response = _post(client, rushed, transcript="this is an entirely different text")
    assert response.status_code == 200
    body = response.json()
    assert body["mode"] == "reject"
    assert body["score"] is None
    assert body["mode_reason"]


def test_audio_without_a_transcript_is_refused(client, rushed):
    """Both halves are required: audio alone cannot be analysed."""
    response = _post(client, rushed, transcript="   ")
    assert response.status_code == 400
    assert "transcript" in response.json()["detail"]


def test_an_oversized_upload_is_refused_before_decoding(client):
    """Spec 15.1: 20 MB. Checked on bytes, so a hostile file is never decoded."""
    response = client.post(
        "/analyze",
        files={"audio": ("big.wav", b"\0" * (21 * MB), "audio/wav")},
        data={"transcript": "hello"},
    )
    assert response.status_code == 413
    assert "20 MB" in response.json()["detail"]


def test_a_non_audio_upload_is_refused_by_extension(client):
    """415 beats handing an arbitrary file to a decoder."""
    response = client.post(
        "/analyze",
        files={"audio": ("notes.txt", b"not audio", "text/plain")},
        data={"transcript": "hello"},
    )
    assert response.status_code == 415


def test_undecodable_audio_is_a_clean_400(client):
    """A .wav that is not a WAV should not surface as a 500 from deep inside."""
    response = client.post(
        "/analyze",
        files={"audio": ("broken.wav", b"RIFFnot-really-a-wav", "audio/wav")},
        data={"transcript": "hello"},
    )
    assert response.status_code == 400
    assert "decoded" in response.json()["detail"]


def test_an_empty_upload_is_refused(client):
    """An empty body is a client mistake, not an analysis."""
    response = client.post(
        "/analyze",
        files={"audio": ("empty.wav", b"", "audio/wav")},
        data={"transcript": "hello"},
    )
    assert response.status_code == 400


