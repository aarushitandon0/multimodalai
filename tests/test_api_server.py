def test_health_reports_the_config_hash_and_versions(client, cfg):
    """A report has to be able to name the exact build that produced it."""
    response = client.get("/health")
    assert response.status_code == 200
    body = response.json()
    assert body["config_hash"] == cfg.hash
    assert body["status"] in {"ok", "degraded"}
    assert body["schema_version"] >= 1
    assert "numpy" in body["packages"]


def test_health_names_mfa_as_the_only_source_of_timing(client):
    """Invariant 4 is a claim the service should be able to substantiate."""
    aligner = client.get("/health").json()["aligner"]
    assert "montreal" in aligner["timing"].lower()
    assert aligner["asr_check_only"] == "faster-whisper"


def test_health_states_the_upload_limits(client, cfg):
    """Spec 15.1: 20 MB and 5 minutes, and a client should be able to read them."""
    limits = client.get("/health").json()["limits"]
    assert limits["max_upload_bytes"] == int(cfg.serving["api"]["max_upload_bytes"])
    assert limits["max_duration_s"] == pytest.approx(300.0)


def test_library_says_which_mode_each_text_would_get(client):
    """A judge should know before uploading whether they get a reference comparison."""
    body = client.get("/library").json()
    assert body["min_references"] >= 1
    for text in body["texts"]:
        expected = (
            "reference"
            if text["has_envelope"] and text["n_references"] >= body["min_references"]
            else "norm"
        )
        assert text["mode"] == expected


def test_library_only_lists_samples_whose_audio_exists(client, cfg):
    """A sample a client cannot fetch is worse than one that is not offered."""
    for sample in client.get("/library").json()["samples"]:
        assert (cfg.root / sample["path"]).is_file()


