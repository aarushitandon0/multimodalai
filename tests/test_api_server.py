def test_analyze_returns_a_reference_mode_result(offline_client, rushed):
    """The whole contract of spec 15.1 in one response."""
    response = _post(offline_client, rushed, text_id="demo_anaphora")
    assert response.status_code == 200
    body = response.json()
    assert body["mode"] == "reference"
    assert body["n_references"] == 5
    assert body["score"]["overall"] > 0
    assert len(body["score"]["categories"]) == 6
    assert body["regions"], "a rushed clause should produce at least one region"


def test_analyze_grounds_every_region_in_time(offline_client, rushed):
    """Temporal grounding is the deliverable; every region must be a real span."""
    body = _post(offline_client, rushed, text_id="demo_anaphora").json()
    duration = body["duration"]
    for region in body["regions"]:
        assert 0.0 <= region["t_start"] < region["t_end"] <= duration + 1e-6
        # Invariant 2: times are rounded to milliseconds in outputs.
        assert region["t_start"] == round(region["t_start"], 3)
        assert region["t_end"] == round(region["t_end"], 3)


def test_every_region_carries_the_numbers_behind_it(offline_client, rushed):
    """Causal explainability: a region without evidence is an opinion."""
    body = _post(offline_client, rushed, text_id="demo_anaphora").json()
    for region in body["regions"]:
        assert region["evidence"], f"region {region['region_id']} has no evidence"
        assert region["rationale"]
        for row in region["evidence"]:
            assert row["feature"]
            assert row["env_sigma"] > 0


def test_analyze_returns_the_curves_the_dashboard_draws(offline_client, rushed):
    """Spec 15.2 needs three panels, per-word deviation and the band."""
    body = _post(offline_client, rushed, text_id="demo_anaphora").json()
    curves = body["curves"]
    assert set(curves["signals"]) >= {"f0_st", "energy_z", "rate_local_syll_per_s"}
    assert curves["words"], "no per-word curves"
    assert curves["deviation"], "no per-word D_w for the coloured transcript"
    assert curves["top_z"], "no per-word z-scores for the transcript hover"
    assert body["envelope_curves"]["words"], "reference mode must carry a band"


def test_the_response_validates_against_the_published_schema(offline_client, rushed):
    """The mirror models must describe what is actually sent."""
    body = _post(offline_client, rushed, text_id="demo_anaphora").json()
    model = AnalysisResultModel.model_validate(body)
    assert model.mode == "reference"
    assert model.alignment is not None
    assert model.alignment.words


def test_the_same_upload_is_served_from_cache(offline_client, rushed):
    """The analysis id is a hash of the bytes, so a repeat costs nothing new."""
    first = _post(offline_client, rushed, text_id="demo_anaphora").json()
    second = _post(offline_client, rushed, text_id="demo_anaphora").json()
    assert first["analysis_id"] == second["analysis_id"]
    assert first == second


