def test_a_cached_analysis_can_be_read_back_by_id(offline_client, rushed):
    """Redrawing a result must not cost a second analysis."""
    body = _post(offline_client, rushed, text_id="demo_anaphora").json()
    again = offline_client.get(f"/analysis/{body['analysis_id']}")
    assert again.status_code == 200
    assert again.json()["analysis_id"] == body["analysis_id"]
    assert again.json()["mode"] == body["mode"]


def test_stage_timings_are_available_for_the_processing_panel(offline_client, rushed):
    """Spec 15.2 shows each stage and what it cost."""
    body = _post(offline_client, rushed, text_id="demo_anaphora").json()
    stages = offline_client.get(f"/stages/{body['analysis_id']}").json()
    assert stages
    names = {s["name"] for s in stages}
    assert {"preprocess", "features"} & names
    assert all(float(s["seconds"]) >= 0 for s in stages)


def test_timings_are_not_part_of_the_hashed_result(offline_client, rushed):
    """Wall-clock numbers must not reach the determinism hash (invariant 13)."""
    body = _post(offline_client, rushed, text_id="demo_anaphora").json()
    assert "stages" not in body
    assert "seconds" not in json.dumps(body["score"])
