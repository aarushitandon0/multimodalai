def test_a_participant_clip_is_a_playable_wav(offline_client, rushed):
    """The A/B player needs bytes a browser can play, at the invariants."""
    import io

    import soundfile as sf

    body = _post(offline_client, rushed, text_id="demo_anaphora").json()
    region = body["regions"][0]
    response = offline_client.get(
        "/clip",
        params={
            "analysis_id": body["analysis_id"],
            "t_start": region["t_start"],
            "t_end": region["t_end"],
            "which": "participant",
        },
    )
    assert response.status_code == 200
    assert response.headers["content-type"] == "audio/wav"

    samples, rate = sf.read(io.BytesIO(response.content))
    assert rate == 16000
    assert samples.ndim == 1
    assert samples.size > 0


def test_a_clip_carries_its_provenance_in_a_header(offline_client, rushed):
    """The dashboard shows which words and which reader without a second request."""
    body = _post(offline_client, rushed, text_id="demo_anaphora").json()
    region = body["regions"][0]
