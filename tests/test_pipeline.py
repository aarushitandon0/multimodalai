def test_two_runs_hash_identically(cfg, library, rushed):
    """CLAUDE.md invariant 13: the same inputs give the same rounded JSON."""
    import hashlib

    digests = []
    for _ in range(2):
        result = analyze(
            rushed.path,
            DEMO_TEXT,
            config=cfg,
            library=library,
            alignment=rushed.alignment,
            check_text_match=False,
            cache=False,
        )
        blob = json.dumps(result.to_dict(), sort_keys=True, separators=(",", ":"))
        digests.append(hashlib.sha256(blob.encode("utf-8")).hexdigest())
    assert digests[0] == digests[1]


def test_the_result_is_cached_and_served_from_cache(cfg, library, rushed, tmp_path):
    overrides = {"paths": {"cache": {"analyses": str(tmp_path / "analyses")}}}
    from rostrum.config import load_config as reload_config

    scoped = reload_config(overrides=overrides)
    first = analyze(
        rushed.path,
        DEMO_TEXT,
        config=scoped,
        library=library,
        alignment=rushed.alignment,
        check_text_match=False,
        cache=True,
    )
    entry = scoped.path("cache.analyses") / f"{first.analysis_id}.json"
    assert entry.is_file()
    payload = json.loads(entry.read_text(encoding="utf-8"))
    assert payload["stages"], "the stage timings are written beside the result"
    second = analyze(
        rushed.path,
        DEMO_TEXT,
        config=scoped,
        library=library,
        alignment=rushed.alignment,
        check_text_match=False,
        cache=True,
    )
    assert second.to_dict() == first.to_dict()


def test_a_cache_entry_from_another_library_is_not_reused(cfg, library, rushed, tmp_path):
    overrides = {"paths": {"cache": {"analyses": str(tmp_path / "analyses")}}}
    from rostrum.config import load_config as reload_config

    scoped = reload_config(overrides=overrides)
    first = analyze(
        rushed.path,
        DEMO_TEXT,
        config=scoped,
        library=library,
        alignment=rushed.alignment,
        check_text_match=False,
        cache=True,
    )
    entry = scoped.path("cache.analyses") / f"{first.analysis_id}.json"
    payload = json.loads(entry.read_text(encoding="utf-8"))
    payload["library_fingerprint"] = "stale"
    entry.write_text(json.dumps(payload), encoding="utf-8")
    again = analyze(
        rushed.path,
        DEMO_TEXT,
        config=scoped,
        library=library,
        alignment=rushed.alignment,
        check_text_match=False,
        cache=True,
    )
    assert again.mode == "reference"


