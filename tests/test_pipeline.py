"""End-to-end tests for :mod:`rostrum.pipeline` (spec 13).

The recordings are generated by :mod:`eval.synthetic_audio` and come with the
alignment the generator laid down, so every stage except MFA itself runs for
real: preprocessing, gap labels from the punctuation, Praat pitch, the frame
grid, the envelope, hysteresis, ruptures refinement, the rubric, the
confidence band, the cards and the DTW-warped curves.

The library is built once per module because extracting features for five
readers costs a few seconds; the tests then analyse different participants
against it.
"""

