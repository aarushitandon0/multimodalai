def test_analysis_id_covers_audio_transcript_and_config():
    a = analyse_id(b"audio", "text", "cfg")
    assert len(a) == 64
    assert a != analyse_id(b"audio2", "text", "cfg")
    assert a != analyse_id(b"audio", "text2", "cfg")
    assert a != analyse_id(b"audio", "text", "cfg2")
    assert a == analyse_id(b"audio", "text", "cfg")


def test_text_similarity_ignores_punctuation_case_and_numerals():
    assert text_similarity("Four score and 7 years ago,", "four score and seven years ago") == 1.0


def test_text_similarity_sees_a_different_text():
    assert text_similarity(DEMO_TEXT, OTHER_TEXT) < 0.5


def test_match_needs_the_threshold(library):
    text_id, score = library.match(DEMO_TEXT, threshold=0.95)
    assert text_id == "demo_anaphora"
    assert score == pytest.approx(1.0)
    assert library.match(OTHER_TEXT, threshold=0.95)[0] is None


def test_match_returns_the_best_score_even_when_it_fails(library):
    text_id, score = library.match(OTHER_TEXT, threshold=0.95)
    assert text_id is None
    assert 0.0 < score < 0.95


def test_the_library_fingerprint_changes_with_its_references(library):
    other = ReferenceLibrary(
        fold=library.fold,
        texts={"t": LibraryText(text_id="t", reference_ids=("a", "b"))},
    )
    assert library.fingerprint() != other.fingerprint()


