def test_a_supplied_alignment_skips_mfa(cfg, library, rushed, monkeypatch):
    """Nothing may call MFA when the caller already has an alignment."""
    import rostrum.align.mfa as mfa_module

    def explode(*args, **kwargs):  # pragma: no cover - must not be reached
        raise AssertionError("MFA was called although an alignment was supplied")

    monkeypatch.setattr(mfa_module, "run_mfa", explode)
    result = analyze(
        rushed.path,
        DEMO_TEXT,
        config=cfg,
        library=library,
        alignment=rushed.alignment,
        check_text_match=False,
        cache=False,
    )
    assert result.alignment is not None
    assert result.alignment.n_words == rushed.alignment.n_words


