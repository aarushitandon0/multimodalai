def test_reference_mode_is_chosen_when_the_text_matches(reference_result):
    assert reference_result.mode == "reference"
    assert reference_result.text_id == "demo_anaphora"
    assert reference_result.n_references == 5
    assert "matches" in reference_result.mode_reason


def test_the_rushed_clause_is_found_where_it_was_put(reference_result, rushed):
    """Words 4-7 were read 1.9x too fast; the region must land on them."""
    words = rushed.alignment.words
    t0, t1 = words[4].t_start, words[7].t_end
    rushing = [r for r in reference_result.regions if r.label == "rushing"]
    assert rushing, [r.label for r in reference_result.regions]
    region = max(rushing, key=lambda r: r.duration)
    assert region.t_start < t1 and region.t_end > t0
    overlap = min(region.t_end, t1) - max(region.t_start, t0)
    assert overlap / (t1 - t0) > 0.5


def test_the_cut_boundary_pause_is_found(reference_result, rushed):
    pauses = [r for r in reference_result.regions if r.label == "missing_pause"]
    assert pauses
    gap = rushed.alignment.gaps[7]
    assert any(abs(r.t_start - gap.t_start) < 0.3 for r in pauses)


def test_every_region_carries_its_evidence_and_sentences(reference_result):
    assert reference_result.regions
    for region in reference_result.regions:
        assert region.evidence
        assert region.rationale and "{" not in region.rationale
        assert region.fix
        assert region.category


def test_a_card_is_written_per_region(reference_result):
    assert len(reference_result.cards) == len(reference_result.regions)
    for card in reference_result.cards:
        assert card["mode"] == "reference"
        assert card["rationale"]
        assert card["evidence"]


def test_the_score_has_six_categories_and_a_band(reference_result):
    score = reference_result.score
    assert score is not None
    assert len(score.categories) == 6
    assert 0.0 <= score.overall <= 10.0
    assert score.overall_band > 0.0  # leave-one-reference-out over five readers


def test_clarity_is_suppressed_not_scored_ten(reference_result):
    """A flaw that could not be looked for is not a flaw that was absent."""
    clarity = reference_result.score.get("clarity")
    assert clarity is not None
    assert clarity.suppressed
    assert "channel" in clarity.suppressed_reason


def test_the_descriptors_carry_the_readers_range(reference_result):
    block = reference_result.score.descriptors
    assert "articulation_rate_syll_s" in block
    assert block["articulation_rate_syll_s"]["n_references"] == 5


def test_the_gap_labels_come_from_the_punctuation(reference_result):
    labels = [g.label for g in reference_result.alignment.gaps]
    # The demo text has one full stop inside it and two commas; the final full
    # stop closes the text and so has no gap after it.
    assert labels.count("boundary") == 1
    assert labels.count("minor") == 2
    assert "none" in labels


def test_curves_are_warped_onto_the_reference_timeline(reference_result):
    curves = reference_result.curves
    assert curves["dtw"] is True
    assert curves["signals"]
    assert len(curves["words"]) == reference_result.alignment.n_words
    first = next(iter(curves["words"].values()))
    assert len(first["values"]) == curves["n_points"]
    band = reference_result.envelope_curves
    assert band["words"]
    assert len(next(iter(band["words"].values()))["median"]) == band["n_points"]


def test_times_are_rounded_to_milliseconds(reference_result):
    payload = reference_result.to_dict()
    for region in payload["regions"]:
        assert region["t_start"] == round(region["t_start"], 3)
        assert region["t_end"] == round(region["t_end"], 3)


def test_the_result_round_trips_through_json(reference_result):
    payload = json.loads(json.dumps(reference_result.to_dict()))
    again = AnalysisResult.from_dict(payload)
    assert again.to_dict() == payload


